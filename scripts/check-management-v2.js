const assert = require("node:assert/strict");
const core = require("../management-core.js");
assert.equal(core.PERSONNEL_COLUMNS.length, 41);
assert.equal(core.VEHICLE_COLUMNS.length, 36);
assert.deepEqual(core.applyEnabledMode(["a","b"], [], ""), ["a","b"]);
assert.deepEqual(core.applyEnabledMode(["a","b"], ["c"], "AGGIUNGI"), ["a","b","c"]);
assert.deepEqual(core.applyEnabledMode(["a","b"], ["b"], "RIMUOVI"), ["a"]);
assert.deepEqual(core.applyEnabledMode(["a","b"], ["c"], "SOSTITUISCI"), ["c"]);
assert.deepEqual(core.legacyEnabledIds({ enabledCommessaIds: [] }, () => "legacy"), []);
assert.deepEqual(core.legacyEnabledIds({ commesseAbilitate: ["Old"] }, v => v === "Old" ? "old-id" : ""), ["old-id"]);
const existing = [{ id:"1", codiceOperatore:"OP1", enabledCommessaIds:["a","b"] }];
const blank = core.validateRow({ CODICE_OPERATORE:"OP1", COMMESSE_ABILITATE:"", MODALITA_AGGIORNAMENTO_COMMESSE:"" }, "personale", existing, v=>v);
assert.deepEqual(blank.finalIds,["a","b"]);
const remove = core.validateRow({ CODICE_OPERATORE:"OP1", COMMESSE_ABILITATE:"b", MODALITA_AGGIORNAMENTO_COMMESSE:"RIMUOVI" }, "personale", existing, v=>v);
assert.deepEqual(remove.finalIds,["a"]);assert.deepEqual(remove.removed,["b"]);
const invalid = core.validateRow({ NOME:"Mario", COGNOME:"Rossi", STATO:"Alieno" }, "personale", [], v=>v);
assert.ok(invalid.errors.some(e=>e.includes("Stato")));
const duplicate = core.identify({ TARGA:"ab123cd" }, [{id:"1",targa:"AB123CD"},{id:"2",targa:"ab123cd"}], "mezzi");
assert.equal(duplicate.duplicate,true);
console.log("Management V2 checks passed");

