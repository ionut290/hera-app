'use strict';
const assert=require('assert');
const fs=require('fs');
const path=require('path');
const cp=require('child_process');
const root=path.join(__dirname,'..');
const header=fs.readFileSync(path.join(root,'header-menu-runtime.js'),'utf8');
const guard=fs.readFileSync(path.join(root,'preventivi-tabs-models-plant-guard.js'),'utf8');
const sw=fs.readFileSync(path.join(root,'sw.js'),'utf8');
['preventivi-models-core.js','preventivi-models-ui.js','preventivi-models-documents.js','preventivi-models-export.js','preventivi-registry-model-export-fix.js','preventivi-registry-model-followup.js'].forEach(file=>assert(header.includes(file),`Modulo mancante nel loader: ${file}`));
assert(header.includes('preventivi-tabs-models-plant-guard.js'),'Guardia Modelli non caricata.');
assert(guard.includes("['models','Modelli']"),'Scheda Modelli non protetta.');
assert(guard.includes('[data-pvm-model-select]'),'Selettore modello non protetto.');
assert(guard.includes("'senza nome'"),'Filtro Senza nome non presente.');
assert(guard.includes('candidateName'),'Recupero denominazione impianto non presente.');
assert(guard.includes('Impianto SAP'),'Fallback ID SAP non presente.');
assert(sw.includes('varga-cantieri-shell-v81'),'Cache PWA non aggiornata.');
assert(sw.includes('preventivi-tabs-models-plant-guard.js?v=20260801a'),'Guardia non presente nella cache PWA.');
cp.execFileSync(process.execPath,['--check',path.join(root,'header-menu-runtime.js')]);
cp.execFileSync(process.execPath,['--check',path.join(root,'preventivi-tabs-models-plant-guard.js')]);
cp.execFileSync(process.execPath,['--check',path.join(root,'sw.js')]);
console.log('check-preventivi-models-visibility: OK');
