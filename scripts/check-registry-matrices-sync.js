"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
const core = require(path.join(root, "management-core.js"));
const ui = fs.readFileSync(path.join(root, "management-v2.js"), "utf8");
const sync = fs.readFileSync(path.join(root, "registry-google-sheet-sync.js"), "utf8");
const apps = fs.readFileSync(path.join(root, "google-apps-script/google-sheet-sync/Code.gs"), "utf8");
const endpoint = require(path.join(root, "netlify/functions/google-sheet-sync.js"));
assert(ui.includes('downloadWorkbook(type,type==="personale"?personaleRecords:mezziRecords)'), "Scarica matrice deve esportare i record correnti");
assert(ui.includes("PERSON_FIELD_MAP") && ui.includes("VEHICLE_FIELD_MAP"), "Le colonne ufficiali devono avere una mappatura completa");
assert(ui.includes('if(value)payload[field]=value'), "Le celle vuote non devono produrre cancellazioni");
assert(ui.includes('action="Invariato"') && ui.includes("Avvisi ${warnings.length}"), "L'anteprima deve distinguere invariati e avvisi");
assert.deepEqual(core.applyEnabledMode(["A"], ["B"], ""), ["A"]);
assert.deepEqual(core.applyEnabledMode(["A"], ["B"], "AGGIUNGI"), ["A", "B"]);
assert.deepEqual(core.applyEnabledMode(["A"], ["B"], "SOSTITUISCI"), ["B"]);
assert.deepEqual(core.applyEnabledMode(["A", "B"], ["B"], "RIMUOVI"), ["A"]);
assert.equal(core.identify({ EMAIL: "mario@example.test" }, [{ id: "p1", email: "mario@example.test" }], "personale").record.id, "p1");
["Collega Foglio Google", "Sincronizza adesso", "Apri Foglio Google", "Impostazioni sincronizzazione", "Scollega Foglio"].forEach((label) => assert(ui.includes(label), label));
["PERSONALE", "MEZZI", "COMMESSE_PERSONALE", "COMMESSE_MEZZI", "LOG_SINCRONIZZAZIONE"].forEach((name) => assert(sync.includes(name), name));
["RECORD_ID", "UPDATED_AT", "UPDATED_BY", "SYNC_VERSION", "SYNC_SOURCE", "ROW_STATUS"].forEach((name) => assert(sync.includes(name), name));
const valid = endpoint.validatePayload({ action: "syncRegistrySpreadsheet", registry: "personale", sheetUrl: "https://docs.google.com/spreadsheets/d/abc_123/edit", sheets: { PERSONALE: [], MEZZI: [], COMMESSE_PERSONALE: [], COMMESSE_MEZZI: [], LOG_SINCRONIZZAZIONE: [] } });
assert.equal(valid.noAutomaticDeletion, true);
console.log("Registry matrices and Google Sheets checks passed.");
